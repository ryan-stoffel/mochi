/* Draws each provider's critter (pet.js, looks.js) on a fake canvas and prints the pixels as Swift for the menu bar
   icon and the notch, so they're always the same critter as the pet. Run from the repo:
   node scripts/tray-sprites.js > Sources/Mochi/Tray/TraySprites.swift */
const fs = require('fs');
const W = require('path').join(__dirname, '../web');
const mkCanvas = () => {
  const c = { width: 0, height: 0, style: {}, px: {}, setAttribute() {}, getBoundingClientRect: () => ({ left: 0, top: 0, width: 46, height: 34 }) };
  const ctx = { fillStyle: '', imageSmoothingEnabled: false,
    fillRect(x, y) { c.px[x + ',' + y] = ctx.fillStyle; }, clearRect() { c.px = {}; }, drawImage() {} };
  c.getContext = () => ctx;
  return c;
};
global.document = { hidden: false, createElement: () => mkCanvas() };
global.window = global;
eval(fs.readFileSync(W + '/pet.js', 'utf8'));
eval(fs.readFileSync(W + '/looks.js', 'utf8'));
const el = { classList: { add() {} }, innerHTML: '', dataset: {}, appendChild() {} };
const SCREENS = { codex: '9', gemini: 'w' };   // the palette letter of each species' face screen
const out = {};
Critter.addPose('iconFine', { anim: 'none' });
Critter.addPose('iconBusy', { eyes: 'dash', anim: 'none' });
Critter.addPose('iconError', { eyes: 'x', anim: 'none' });
Critter.addPose('iconBack', { eyes: 'none', anim: 'none' });   // no face: what's left where the eyes were is the eyes
for (const [id, L] of Object.entries(MINI_LOOKS)) {
  out[id] = {};
  for (const mood of ['Fine', 'Busy', 'Error', 'Back']) {
    const c = new Critter(el, { pose: 'icon' + mood, scale: 1, blink: false, particles: false, species: L.species, palette: L.palette });
    const px = Object.assign({}, c.buf.px);
    c.destroy();
    // drop the ground shadow (translucent)
    for (const k of Object.keys(px)) if (String(px[k]).startsWith('rgba')) delete px[k];
    out[id][mood.toLowerCase()] = px;
  }
}
// One Swift literal per provider: its palette, then rows of palette letters for each mood.
const letters = 'abcdefghijklmnopqrstuvwxyz';
let swift = '// Generated by scripts/tray-sprites.js from web/pet.js and looks.js. Don\'t edit; rerun it:\n' +
  '//   node scripts/tray-sprites.js > Sources/Mochi/Tray/TraySprites.swift\n\n' +
  '/// Each provider\'s critter standing still: a palette and rows of palette letters per mood (the notch), and a\n' +
  '/// one-colour silhouette with its eyes cut out, `#` filled and `.` clear (the menu bar\'s template icon).\n' +
  'enum TraySprites {\n    struct Sprite { let palette: [String]; let fine: [String]; let busy: [String]; let error: [String]; let template: [String] }\n\n' +
  '    static let all: [String: Sprite] = [\n';
for (const [id, moods] of Object.entries(out)) {
  const back = moods.back;
  delete moods.back;
  const all = Object.values(moods).flatMap((m) => Object.keys(m).map((k) => k.split(',').map(Number)));
  const x0 = Math.min(...all.map((p) => p[0])), x1 = Math.max(...all.map((p) => p[0]));
  const y0 = Math.min(...all.map((p) => p[1])), y1 = Math.max(...all.map((p) => p[1]));
  const colors = [...new Set(Object.values(moods).flatMap((m) => Object.values(m)))];
  const rows = (m) => Array.from({ length: y1 - y0 + 1 }, (_, j) => Array.from({ length: x1 - x0 + 1 }, (_, i) => {
    const c = m[(x0 + i) + ',' + (y0 + j)];
    return c ? letters[colors.indexOf(c)] : '.';
  }).join(''));
  // the menu bar's monochrome silhouette: every pixel of the critter, less its eyes. A face screen (Codex's visor,
  // Gemini's face) is cut out instead, with the eyes left standing in it.
  const letter = SCREENS[MINI_LOOKS[id].species];
  const screen = letter && ((MINI_LOOKS[id].palette || {})[letter] || Critter.PAL[letter]);
  const template = Array.from({ length: y1 - y0 + 1 }, (_, j) => Array.from({ length: x1 - x0 + 1 }, (_, i) => {
    const k = (x0 + i) + ',' + (y0 + j), body = back[k], eye = moods.fine[k] && moods.fine[k] !== body;
    if (screen && body === screen) return eye ? '#' : '.';
    return moods.fine[k] && !eye ? '#' : '.';
  }).join(''));
  const list = (r) => '[\n' + r.map((s) => '            "' + s + '",').join('\n') + '\n        ]';
  swift += `        "${id}": Sprite(\n        palette: [${colors.map((c) => '"' + c + '"').join(', ')}],\n` +
    `        fine: ${list(rows(moods.fine))},\n        busy: ${list(rows(moods.busy))},\n        error: ${list(rows(moods.error))},\n` +
    `        template: ${list(template)}),\n`;
}
swift += '    ]\n}\n';
process.stdout.write(swift);
process.exit(0);
